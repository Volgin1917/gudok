def counts(methods=None):
    """Счётчики реестра: всего, работают, в тесте, в очереди, идеологический блок."""
    methods = METHODS if methods is None else methods
    out = {"total": len(methods), "work": 0, "test": 0, "queue": 0, "ideo": 0}
    for m in methods:
        st = m.get("status") if m.get("status") in STATUS else "queue"
        out[st] += 1
        if m.get("ideo"):
            out["ideo"] += 1
    out["standards"] = len(TECH_STANDARDS["rows"])
    return out


def by_group(methods=None):
    """Методики по группам с сохранением порядка GROUPS (идеологический блок — сквозной)."""
    methods = METHODS if methods is None else methods
    out = {k: [] for k, _t, _s in GROUPS}
    for m in methods:
        out.setdefault(m.get("group", "present"), []).append(m)
    return out


def code_num(code):
    """Число из кода методики: «М-21» -> 21 (для сортировки)."""
    m = re.search(r"(\d+)", code or "")
    return int(m.group(1)) if m else 0


def sorted_by_code(methods=None):
    return sorted(METHODS if methods is None else methods, key=lambda m: code_num(m.get("code")))


def wilson_pp(n, z=1.96, p=0.5):
    """Погрешность в процентных пунктах при worst-case p=0.5 (нормальное приближение).

    Для детерминированных и качественных процедур (n пустое или «—») интервал
    не применяется — так и пишем, чтобы не создавать ложной точности."""
    try:
        n = int(str(n).strip())
    except (TypeError, ValueError):
        return "детерминированная/качественная процедура — интервал не применяется"
    if n <= 0:
        return "детерминированная/качественная процедура — интервал не применяется"
    return f"интервал Уилсона 95%: при n={n} погрешность ≈ ±{z * math.sqrt(p * (1 - p) / n) * 100:.1f} пп"


def row_of(m, label):
    """Поле паспорта по названию: «Метрики качества», «Вход», «Неопределённость»…"""
    for r in m.get("rows", []):
        if r.get("label") == label:
            return r.get("text", "")
    return ""


def steps_of(m, label="Порядок проверки на платформе"):
    for r in m.get("rows", []):
        if r.get("label") == label:
            return r.get("steps", [])
    return []


