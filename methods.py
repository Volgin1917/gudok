def protocol(m, size=200, seed=42, date_str=""):
    """Текст протокола испытания методики — серверный аналог стенда на странице.

    Совпадает с тем, что формирует кнопка «Сформировать протокол»: тот же порядок
    шагов, та же оценка неопределённости, те же подписи. Нужен для тестов и для
    автоматической генерации протокола в конвейере."""
    st = STATUS.get(m.get("status"), "очередь")
    metrics = row_of(m, "Метрики качества").rstrip(".")
    mod = m.get("mod", "—")
    lines = [
        "ПРОТОКОЛ ИСПЫТАНИЯ МЕТОДИКИ",
        f"Код: {m.get('code','')} · Название: {m.get('name','')}",
        f"Текущий статус: {st} · Платформа: «Гудок», контур анализа инфополя",
        (f"Выборка: {size} единиц (случайная из архива, seed={seed}); "
         f"минимум по паспорту: n={m.get('n','—')}"),
        "Разметка: два редактора независимо, расхождения — третий; каппа фиксируется",
        "Шаги:",
        " 1. Выгрузить выборку из базы (SQLite; экспорт CSV по RFC 4180).",
        " 2. Разметить вручную по инструкции методики.",
        f" 3. Прогнать модуль: {mod}.",
        f" 4. Посчитать метрики: {metrics}.",
        f" 5. Неопределённость: {wilson_pp(m.get('n'))}.",
        " 6. Критерий приёмки: порог ≥ 0.80 с учётом интервала; повторный прогон без расхождений.",
        " 7. Вердикт внести в реестр (methods.html), запись — в методологический журнал (М-28).",
        f"Дата: {date_str} · Подписи: аналитик ______ редактор ______",
    ]
    return "\n".join(lines)


def by_sub(methods=None):
    """Методики по группам и подгруппам: {group: {sub: [m, …]}} в порядке SUBGROUPS.

    Внутри подгруппы — сортировка по статусу (работает → тест → очередь), затем по коду.
    """
    ms = METHODS if methods is None else methods
    out = {}
    for gkey, subs in SUBGROUPS.items():
        out[gkey] = {s: [] for s, _t in subs}
        for m in ms:
            if m.get("group") == gkey:
                out[gkey].setdefault(m.get("sub", ""), []).append(m)
    for gkey in out:
        for s in out[gkey]:
            out[gkey][s].sort(key=lambda m: (STATUS_RANK.get(m.get("status"), 9),
                                             code_num(m.get("code", ""))))
    return out


def sorted_by_status(methods=None):
    """Сортировка реестра: порядок групп GROUPS, внутри — статус (work → test → queue), затем код."""
    ms = METHODS if methods is None else methods
    gorder = {k: i for i, (k, _t, _s) in enumerate(GROUPS)}
    return sorted(ms, key=lambda m: (gorder.get(m.get("group"), 99),
                                     STATUS_RANK.get(m.get("status"), 9),
                                     code_num(m.get("code", ""))))


