REQUIRED_CORE = ("code", "group", "status", "id", "name", "ess", "kind", "sub", "owner",
                 "status_since", "source")


def validate(m, codes=None):
    """Машинная валидация паспорта (v2.0): список ошибок, пустой — паспорт корректен.

    Правило редакции: паспорт, не прошедший валидацию, не может быть в статусе «работает».
    codes — множество кодов реестра для проверки перекрёстных ссылок (validate_registry).
    """
    errs = []
    code = m.get("code", "?")
    for f in REQUIRED_CORE:
        if not str(m.get(f, "")).strip():
            errs.append(f"{code}: пусто обязательное поле {f}")
    if m.get("status") not in STATUS:
        errs.append(f"{code}: неизвестный статус {m.get('status')!r}")
    if m.get("kind") not in KINDS:
        errs.append(f"{code}: неизвестный тип паспорта {m.get('kind')!r}")
    if m.get("group") not in GROUP_TITLE:
        errs.append(f"{code}: неизвестная группа {m.get('group')!r}")
    elif m.get("sub") not in dict(SUBGROUPS.get(m["group"], [])):
        errs.append(f"{code}: подгруппа {m.get('sub')!r} не из списка группы {m['group']}")
    if m.get("owner") not in OWNERS:
        errs.append(f"{code}: владелец {m.get('owner')!r} не из ролей {OWNERS}")
    # шесть строк паспорта — состав не меняется
    labels = {r.get("label") for r in m.get("rows", [])}
    need = {"Вход", "Выход", "Метрики качества", "Модуль платформы", "Неопределённость",
            "Порядок проверки на платформе"}
    if labels != need:
        errs.append(f"{code}: состав строк паспорта отличается от {sorted(need)}")
    # зависимые поля по типу
    for f in KIND_FIELDS.get(m.get("kind"), ()):
        if not str(m.get(f, "")).strip():
            errs.append(f"{code}: тип «{KINDS.get(m.get('kind'))}» требует поле {f}")
    # ограничения и связанность
    lim = m.get("limitations") or []
    if not lim or not all(str(x).strip() for x in lim):
        errs.append(f"{code}: ограничения (limitations) — непустой список строк")
    deps = m.get("dependencies") or {}
    if not (deps.get("data") or []):
        errs.append(f"{code}: dependencies.data — непустой список источников данных")
    if codes is not None:
        for ref in (deps.get("methods") or []) + (m.get("related") or []):
            if ref not in codes:
                errs.append(f"{code}: ссылка на несуществующую методику {ref}")
        if code in (m.get("related") or []):
            errs.append(f"{code}: related содержит сам себя")
    # очередь — чем блокируется; не очередь — blocked_by отсутствует
    blocked = m.get("blocked_by") or []
    if m.get("status") == "queue":
        if not blocked:
            errs.append(f"{code}: очередь без blocked_by — что именно блокирует?")
        for b in blocked:
            if b not in BLOCKED_BY:
                errs.append(f"{code}: неизвестная причина блокировки {b!r}")
    elif blocked:
        errs.append(f"{code}: blocked_by допускается только у статуса «очередь»")
    # «работает» — только с примером расчёта
    if m.get("status") == "work" and not str(m.get("example", "")).strip():
        errs.append(f"{code}: статус «работает» требует пример расчёта (example)")
    return errs


def validate_registry():
    """Валидация всего реестра: паспорта + перекрёстные ссылки + уникальность id/кодов.

    Возвращает список ошибок (пустой — реестр корректен). Используется тестами и будущим
    веб-стендом (панель «конвейер редакции», server_plan.md этап B2).
    """
    errs = []
    codes = [m.get("code") for m in METHODS]
    ids = [m.get("id") for m in METHODS]
    if len(set(codes)) != len(codes):
        errs.append("реестр: повторяющиеся коды методик")
    if len(set(ids)) != len(ids):
        errs.append("реестр: повторяющиеся id якорей")
    codeset = set(codes)
    for m in METHODS:
        errs.extend(validate(m, codeset))
    # каждая подгруппа непуста; порядок кодов внутри реестра не важен — важен охват
    covered = {(m.get("group"), m.get("sub")) for m in METHODS}
    for gkey, subs in SUBGROUPS.items():
        for s, _t in subs:
            if (gkey, s) not in covered:
                errs.append(f"реестр: подгруппа {gkey}/{s} пуста")
    for slug, _term, _defn in GLOSSARY:
        if not re.fullmatch(r"[a-z0-9-]+", slug):
            errs.append(f"глоссарий: недопустимый slug {slug!r}")
    return errs
