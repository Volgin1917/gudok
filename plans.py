def _num(x):
    """Целое с неразрывными пробелами разрядов: 2 432."""
    try:
        return f"{int(x):,}".replace(",", " ")
    except (TypeError, ValueError):
        return "—"


def _f(x, digits=1):
    """Дробное число с фиксированной точкой: 29.7."""
    try:
        return f"{float(x):.{digits}f}"
    except (TypeError, ValueError):
        return "—"


def _pct(x, digits=1):
    """Доля в процентах: 0.248 → 24.8%."""
    try:
        return f"{float(x) * 100:.{digits}f}%"
    except (TypeError, ValueError):
        return "—"


