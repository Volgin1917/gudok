def _clean(s):
    """Убирает markdown-разметку из строки: **жирный**, `код`, ссылки [текст](url)."""
    s = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", s or "")
    s = re.sub(r"\*\*(.+?)\*\*", r"\1", s)
    s = re.sub(r"`([^`]+)`", r"\1", s)
    return re.sub(r"\s+", " ", s).strip()


def md_outline(text):
    """Документ как список (уровень, заголовок, тело) — для поиска разделов."""
    out = []
    level, title, buf = 0, "", []
    for line in (text or "").splitlines():
        m = MD_HEAD_RE.match(line)
        if m:
            if title or buf:
                out.append((level, title, "\n".join(buf)))
            level, title, buf = len(m.group(1)), _clean(m.group(2)), []
        else:
            buf.append(line)
    out.append((level, title, "\n".join(buf)))
    return out


def md_section(text, prefix):
    """Тело первого раздела, заголовок которого начинается с prefix."""
    for _lvl, title, body in md_outline(text):
        if title.startswith(prefix):
            return body
    return ""


def md_table(body):
    """Первая markdown-таблица в блоке: (заголовки, строки)."""
    rows = []
    for line in (body or "").splitlines():
        s = line.strip()
        if not s.startswith("|"):
            if rows:
                break
            continue
        cells = [_clean(c) for c in s.strip("|").split("|")]
        if cells and all(MD_SEP_RE.match(c or "-") for c in cells):
            continue
        rows.append(cells)
    if not rows:
        return [], []
    return rows[0], rows[1:]


def checklist(text, only_open=False):
    """Пункты-чекбоксы с ближайшим заголовком раздела: [{section, done, partial, text}]."""
    items = []
    section = ""
    for line in (text or "").splitlines():
        head = MD_HEAD_RE.match(line)
        if head:
            section = _clean(head.group(2))
            continue
        m = MD_ITEM_RE.match(line)
        if not m:
            continue
        mark = m.group(2).lower()
        done = mark in ("x", "~")
        if only_open and done:
            continue
        items.append({"section": section, "done": done, "partial": mark == "~",
                      "text": _clean(m.group(3))})
    return items


def roadmap_open():
    """Открытые пункты ROADMAP.md, сгруппированные по разделам."""
    items = checklist(read_md("ROADMAP.md"), only_open=True)
    out = []
    for it in items:
        if out and out[-1]["section"] == it["section"]:
            out[-1]["items"].append(it)
        else:
            out.append({"section": it["section"], "items": [it]})
    return out


def roadmap_version(text=None):
    """Строка версии документа ROADMAP.md («Версия документа: 3.0 · 16.09.2026 …»)."""
    src = text if text is not None else read_md("ROADMAP.md")
    m = re.search(r"Версия документа:\s*([^\n·]+)·\s*([^\n:]{4,40})", src)
    return (m.group(1).strip(), m.group(2).strip()) if m else ("", "")


def server_stages():
    """Этапы миграции из server_plan.md §7: [{stage, term, content, ready}]."""
    _head, rows = md_table(md_section(read_md("server_plan.md"), "7."))
    out = []
    for r in rows:
        if len(r) < 4:
            continue
        out.append({"stage": r[0], "term": r[1], "content": r[2], "ready": r[3]})
    return out


def server_choices():
    """Точки выбора из server_plan.md §10: (решено, открыто)."""
    body = md_section(read_md("server_plan.md"), "10.")
    decided, opened, bucket = [], [], None
    for line in body.splitlines():
        low = line.lower()
        if "решено" in low:
            bucket = decided
            continue
        if "открыт" in low and line.strip().startswith("**"):
            bucket = opened
            continue
        m = MD_NUM_RE.match(line)
        if m and bucket is not None:
            bucket.append(_clean(m.group(2)))
    return decided, opened


def frontpage_sprints():
    """Спринты plan_frontpage_v4.md: заголовок, пункты со статусами, счётчик готового."""
    out = []
    for _lvl, title, body in md_outline(read_md("plan_frontpage_v4.md")):
        if not title.startswith("Спринт"):
            continue
        _head, rows = md_table(body)
        items = []
        for r in rows:
            if len(r) < 3:
                continue
            items.append({"no": r[0], "proposal": r[1], "status": r[2],
                          "note": r[3] if len(r) > 3 else ""})
        done = sum(1 for i in items if i["status"].lower().startswith("готово"))
        out.append({"title": title, "items": items, "done": done, "total": len(items)})
    return out


def counts(reg=None):
    """Счётчики статусов реестра метрик + общее число кандидатов."""
    reg = REG if reg is None else reg
    out = {k: 0 for k in STATUS}
    for r in reg:
        st = r.get("st") if r.get("st") in STATUS else "queue"
        out[st] += 1
    out["total"] = len(reg)
    return out


def by_axis(reg=None):
    """Метрики по осям: {ось: {статус: число}} — для полосы готовности разделов."""
    reg = REG if reg is None else reg
    out = {}
    for r in reg:
        ax = r.get("ax", "method")
        row = out.setdefault(ax, {k: 0 for k in STATUS})
        row[r.get("st") if r.get("st") in STATUS else "queue"] += 1
        row["total"] = row.get("total", 0) + 1
    return out
