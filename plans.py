def roadmap_version(text=None):
    """Строка версии документа ROADMAP.md («Версия документа: 3.0 · 16.09.2026 …»)."""
    src = text if text is not None else read_md("ROADMAP.md")
    m = re.search(r"Версия документа:\s*([^\n·]+)·\s*([^\n:]{4,40})", src)
    return (m.group(1).strip(), m.group(2).strip()) if m else ("", "")


