def server_choices():
    """Точки выбора из server_plan.md §10: (решено, открыто)."""
    body = md_section(read_md("server_plan.md"), "10.")
    decided, opened, bucket = [], [], None
    for line in body.splitlines():
        low = line.lower()
        if "решено" in low:
            bucket = decided
            continue
        if "открыт" in low and line.strip().startswith("**"):
            bucket = opened
            continue
        m = MD_NUM_RE.match(line)
        if m and bucket is not None:
            bucket.append(_clean(m.group(2)))
    return decided, opened


