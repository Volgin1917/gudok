def counts(persons=None):
    """Счётчики раздела: персон, в фокусе, новых, упоминаний за 30 дней, сюжетов."""
    persons = PERSONS if persons is None else persons
    out = {"persons": len(persons), "focus": 0, "new": 0, "back": 0,
           "mentions": 0, "stories": 0, "sources": set()}
    for p in persons:
        st = p.get("status") if p.get("status") in STATUS_TITLE else "back"
        out[st] += 1
        out["mentions"] += int(p.get("mentions") or 0)
        out["stories"] += len(p.get("stories") or [])
        for name, _n in p.get("sources") or []:
            out["sources"].add(name)
    out["sources_n"] = len(out["sources"])
    out.pop("sources")
    return out


def by_role(persons=None):
    """Число карточек по ролям — для подписей кнопок фильтра."""
    persons = PERSONS if persons is None else persons
    out = {k: 0 for k, _t in ROLES}
    for p in persons:
        out[p.get("group")] = out.get(p.get("group"), 0) + 1
    return out


def sorted_by_mentions(persons=None):
    """Карточки по убыванию упоминаний — порядок вывода на странице."""
    return sorted(PERSONS if persons is None else persons,
                  key=lambda p: -int(p.get("mentions") or 0))


def initials(name):
    """Инициалы для аватара: «Иванов Иван Иванович» → «ИИ» (фамилия + имя)."""
    parts = [w for w in (name or "").replace("«", " ").replace("»", " ").split() if w[:1].isupper()]
    if len(parts) >= 2:
        return (parts[0][0] + parts[1][0]).upper()
    return (parts[0][:2].upper() if parts else "??")
